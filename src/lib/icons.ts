export const icons: Record<string, IconType> = Object.assign({}, ...Object.values(iconGroups));

export const iconNames = Object.keys(icons);

export function isIconName(name: string): boolean {
  return Object.hasOwn(icons, name);
}

/** Resolves a stored icon name, falling back so a renamed icon never breaks a page. */
export function getIcon(name: string | undefined, fallback: IconType = FaCode): IconType {
  return (name && icons[name]) || fallback;
}
